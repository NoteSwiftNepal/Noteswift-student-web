import api from "@/api/axios";
import type { PriceQuote } from "@/api/student/checkout";

// The student's own successful online payments (backend paymentsController).
export interface Payment {
  _id: string;
  courseId: string;
  courseTitle: string;
  amount: number;
  paymentMethod: "fonepay" | "esewa-gateway" | "connectips" | string;
  reference?: string;
  paidAt: string;
  receiptNumber?: string;
  // Frozen at payment time; null for payments made before breakdowns existed.
  pricing: PriceQuote | null;
}

export const getMyPayments = async (): Promise<Payment[]> => {
  const res = await api.get("/learn/payments");
  if (!res.data?.success) throw new Error(res.data?.message || "Could not load your payments");
  return res.data.data;
};

// The PDF receipt (generated by the backend). Downloaded through axios so the
// login header is sent, then saved via a temporary object URL.
export const downloadReceipt = async (payment: Payment): Promise<void> => {
  const res = await api.get(`/learn/payments/${payment._id}/receipt`, { responseType: "blob" });
  const disposition: string = res.headers["content-disposition"] || "";
  const filename = /filename="([^"]+)"/.exec(disposition)?.[1] || `NoteSwift-receipt-${payment._id}.pdf`;
  const url = URL.createObjectURL(res.data as Blob);
  try {
    const a = document.createElement("a");
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    a.remove();
  } finally {
    setTimeout(() => URL.revokeObjectURL(url), 10_000);
  }
};
